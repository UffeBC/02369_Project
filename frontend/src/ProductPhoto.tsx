export default function ProductPhoto({ name }: { name: string }) {
  const [failed, setFailed] = useState(false)
  const id = photoIds.get(name)
  if (failed || !id) return <span className="product-photo photo-placeholder" aria-hidden="true">{name[0]}</span>
  return <img className="product-photo" src={`${imageRoot}${id}-cr-225x160.jpeg`} alt="" loading="lazy" referrerPolicy="no-referrer" onError={() => setFailed(true)} />
}
